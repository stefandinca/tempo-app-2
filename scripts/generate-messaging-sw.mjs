#!/usr/bin/env node
/**
 * Generates public/firebase-messaging-sw.js from the template, injecting the
 * Firebase config of the tenant currently being built.
 *
 * Why this exists: the service worker used to hardcode the live project. It is
 * served per-deployment, so every tenant's browser initialised FCM against
 * `tempo-app-2`. The foreground messaging instance uses the correct per-tenant
 * config from env, so the two disagreed — and a mismatched `messagingSenderId`
 * means the worker rejects the push messages that tenant's own Cloud Function
 * sends. Background notifications simply never arrive.
 *
 * Run automatically by scripts/tenant-env.mjs once the tenant's env is resolved,
 * so it cannot be forgotten on either the local or the Vercel build path.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const TEMPLATE = path.join(ROOT, "public", "firebase-messaging-sw.template.js");
const OUTPUT = path.join(ROOT, "public", "firebase-messaging-sw.js");

const FIELDS = {
  apiKey: "NEXT_PUBLIC_FIREBASE_API_KEY",
  authDomain: "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN",
  projectId: "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  storageBucket: "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET",
  messagingSenderId: "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  appId: "NEXT_PUBLIC_FIREBASE_APP_ID",
};

export function generateMessagingSw(env = process.env) {
  if (!existsSync(TEMPLATE)) {
    throw new Error(`Missing ${path.relative(ROOT, TEMPLATE)} — cannot generate the messaging service worker.`);
  }

  const config = {};
  const missing = [];
  for (const [key, envVar] of Object.entries(FIELDS)) {
    const v = env[envVar];
    if (!v) missing.push(envVar);
    config[key] = v || "";
  }
  if (missing.length) {
    // Failing loudly matters: a silently wrong service worker looks fine until
    // someone notices push has been dead for weeks.
    throw new Error(
      `Cannot generate the messaging service worker — missing ${missing.join(", ")}.`,
    );
  }

  const template = readFileSync(TEMPLATE, "utf8");
  // Newline-agnostic: the template may be checked out with CRLF on Windows, and a
  // \n-anchored match would silently leave the "TEMPLATE — do not edit" banner on
  // the generated file.
  const body = template
    .replace(
      /^\/\/ TEMPLATE[^\n]*\r?\n\/\/ Edit this file[^\n]*\r?\n/,
      `// GENERATED by scripts/generate-messaging-sw.mjs — do not edit.\n` +
        `// Edit public/firebase-messaging-sw.template.js instead.\n` +
        `// Tenant: ${config.projectId}\n`,
    )
    .replace("__FIREBASE_CONFIG__", JSON.stringify(config, null, 2));

  if (body.includes("// TEMPLATE —")) {
    throw new Error("Template banner was not replaced — the generated file would claim to be the template.");
  }

  if (body.includes("__FIREBASE_CONFIG__")) {
    throw new Error("Template placeholder __FIREBASE_CONFIG__ was not replaced.");
  }

  writeFileSync(OUTPUT, body, "utf8");
  return config.projectId;
}

// Allow running standalone: node scripts/generate-messaging-sw.mjs
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  try {
    const project = generateMessagingSw();
    console.log(`generated public/firebase-messaging-sw.js for ${project}`);
  } catch (err) {
    console.error(`\x1b[31m✗ ${err.message}\x1b[0m`);
    process.exit(1);
  }
}
